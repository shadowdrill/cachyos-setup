#!/usr/bin/env bash
# Write /etc/fah-client/config.xml for this machine.
#
# Team 223518 (Linus Tech Tips) is hard-coded — that is the only team the
# cachyos-setup repo folds for. Passkey is read from
#   $XDG_CONFIG_HOME/foldingathome/passkey   (default ~/.config/foldingathome/passkey)
# which is gitignored by cachyos-setup and must be chmod 600.
#
# Username defaults to <hostname>-folding so points are tracked per-machine.
# Override with FOLDING_USER=... if you want a custom name.
#
# GPU folding is enabled automatically when nvidia-smi is present and
# reports at least one device. Force off with FOLDING_GPU=0.
#
# Usage:
#   ./configure.sh                       # write config and restart service
#   ./configure.sh --no-restart          # write config only
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

TEAM=223518
TEAM_NAME="LinusTechTips_Team"
HOSTNAME_SHORT="$(hostname -s 2>/dev/null || hostname)"
USER_NAME="${FOLDING_USER:-${HOSTNAME_SHORT}-folding}"

GPU_ENABLE=auto
for arg in "$@"; do
    case "${arg}" in
        --no-restart) NO_RESTART=1 ;;
        -h|--help)
            sed -n '2,18p' "${BASH_SOURCE[0]}" | sed 's/^# *//'
            exit 0
            ;;
        *) echo "Unknown arg: ${arg}" >&2; exit 2 ;;
    esac
done
[[ "${FOLDING_GPU:-}" == "0" ]] && GPU_ENABLE=0
[[ "${FOLDING_GPU:-}" == "1" ]] && GPU_ENABLE=1

CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/foldingathome"
PASSKEY_FILE="${CONFIG_DIR}/passkey"
TARGET="/etc/fah-client/config.xml"
BACKUP="/etc/fah-client/config.xml.bak.$(date +%Y%m%d-%H%M%S)"

if [[ $EUID -eq 0 ]]; then
    echo "Do not run as root; the script will sudo when it needs to." >&2
    exit 1
fi

# --- passkey ---
if [[ ! -s "${PASSKEY_FILE}" ]]; then
    cat <<EOF >&2
No passkey found at ${PASSKEY_FILE}.

Get one (one per user, valid on every machine):
  1. Open https://apps.foldingathome.org/passkey
  2. Fill in username (any name; this is just to attribute points to you,
     not the per-machine name) and a valid email; submit.
  3. Copy the 32-character passkey the page shows.

Then save it to a file the script can read:
  mkdir -p '${CONFIG_DIR}'
  chmod 700 '${CONFIG_DIR}'
  umask 077
  cat > '${PASSKEY_FILE}' <<<"<paste your passkey here>"
  chmod 600 '${PASSKEY_FILE}'

Re-run this script.
EOF
    exit 1
fi
chmod 600 "${PASSKEY_FILE}"
PASSKEY="$(tr -d '[:space:]' < "${PASSKEY_FILE}")"
if [[ ! "${PASSKEY}" =~ ^[A-Fa-f0-9]{32}$ ]]; then
    echo "Passkey in ${PASSKEY_FILE} is not 32 hex characters; refusing to proceed." >&2
    echo "Got: ${PASSKEY}" >&2
    exit 1
fi

# --- GPU detection ---
gpu_slot=""
gpu_count=0
case "${GPU_ENABLE}" in
    0)  gpu_slot="" ;;
    1)
        if command -v nvidia-smi >/dev/null 2>&1; then
            gpu_count="$(nvidia-smi --query-gpu=index --format=csv,noheader 2>/dev/null | wc -l)"
        fi
        ;;
    auto)
        if command -v nvidia-smi >/dev/null 2>&1; then
            gpu_count="$(nvidia-smi --query-gpu=index --format=csv,noheader 2>/dev/null | wc -l)"
        fi
        ;;
esac
if (( gpu_count > 0 )); then
    gpu_slots_block=""
    for ((i=0; i<gpu_count; i++)); do
        # Append an explicit \n because $(...) command substitution strips trailing newlines,
        # which would otherwise jam the next slot against the previous </slot>.
        gpu_slots_block+=$(
            cat <<GPU_SLOT
    <slot v="gpu${i}" type="GPU">
      <cpus v="-1"/>
    </slot>
GPU_SLOT
        )$'\n'
    done
fi

# --- write config.xml ---
{
    cat <<XML_HEADER
<config>
  <!-- Generated by cachyos-setup/scripts/folding/configure.sh on $(date -Iseconds) -->
  <!-- Edit by re-running the script, not by hand, so the gitignored passkey is reused. -->
  <user v="${USER_NAME}"/>
  <team v="${TEAM}"/>
  <passkey v="${PASSKEY}"/>
  <project-key v=""/>
  <slots>
    <slot v="cpu" type="CPU">
      <cpus v="-1"/>
    </slot>
XML_HEADER
    if [[ -n "${gpu_slots_block}" ]]; then
        printf '%s' "${gpu_slots_block}"
    fi
    cat <<XML_FOOTER
  </slots>
  <power v="MEDIUM"/>
  <cause v="ANY"/>
</config>
XML_FOOTER
} > /tmp/fah-config.xml.new

# sanity-check the XML is well-formed before sudo
if ! command -v xmllint >/dev/null 2>&1; then
    if command -v python3 >/dev/null 2>&1; then
        python3 -c "import xml.etree.ElementTree as ET; ET.parse('/tmp/fah-config.xml.new')" || {
            echo "Generated config.xml is not well-formed XML; aborting." >&2
            cat /tmp/fah-config.xml.new >&2
            exit 1
        }
    fi
else
    xmllint --noout /tmp/fah-config.xml.new || {
        echo "Generated config.xml is not well-formed XML; aborting." >&2
        cat /tmp/fah-config.xml.new >&2
        exit 1
    }
fi

echo ">>> Backing up ${TARGET} -> ${BACKUP} (if it exists)"
if [[ -f "${TARGET}" ]]; then
    sudo cp -a "${TARGET}" "${BACKUP}"
fi

echo ">>> Writing ${TARGET}"
sudo install -d -m 0755 -o fah-client -g fah-client "$(dirname "${TARGET}")"
sudo install -m 0644 -o fah-client -g fah-client /tmp/fah-config.xml.new "${TARGET}"
rm -f /tmp/fah-config.xml.new

echo
echo "New ${TARGET}:"
sudo cat "${TARGET}"

if [[ "${NO_RESTART:-0}" -eq 1 ]]; then
    echo
    echo "Skipping service restart (--no-restart)."
    echo "Run when ready:  sudo systemctl restart fah-client.service"
    exit 0
fi

echo
echo ">>> Restarting fah-client.service"
sudo systemctl restart fah-client.service
sleep 3
echo
echo "Service status:"
systemctl is-active fah-client.service
echo
echo "Recent log:"
sudo journalctl -u fah-client.service --no-pager -n 8
echo
echo "Web control panel:  http://localhost:7396/"
echo "(forward that port over SSH for remote control:  ssh -L 7396:localhost:7396 user@host)"
